    public static readonly IReadOnlyList<(Guid Id, string Name, string Icon, int SortOrder, bool IsFallback)> Departments =
        Source
            .Select((d, index) => (SeedIds.Department(d.Name), d.Name, d.Icon, (index + 1) * 10, d.Name == FallbackName))
            .ToList();

    /// <summary>Normalised, the first occurrence of a keyword wins (the sheet repeats «семг» as «сёмг» and «мед» as «мёд»).</summary>
    public static readonly IReadOnlyList<(Guid Id, string Keyword, Guid DepartmentId)> Keywords =
        Source
            .SelectMany(d => d.Keywords
                .Split('|', StringSplitOptions.RemoveEmptyEntries)
                .Select(k => (Keyword: NameNormalizer.Normalize(k), DepartmentId: SeedIds.Department(d.Name))))
            .DistinctBy(k => k.Keyword)
            .Select(k => (SeedIds.Keyword(k.Keyword), k.Keyword, k.DepartmentId))
            .ToList();
